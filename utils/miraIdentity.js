/**
 * @param {string} [userMessage]
 */
export function isMiraStoryQuestion(userMessage) {
  const m = String(userMessage || '').trim();
  if (!m) return false;
  if (isMiraBirthdayQuestion(m)) return false;
  if (/Mira.?ရဲ့.?အကြောင်း|မီရာ.?ရဲ့.?အကြောင်း|mira.?ရဲ့.?အကြောင်း/i.test(m)) return true;
  if (/tell me about mira|who are you[,!.\s]*mira|mira[,!.\s]*who are you|who is mira|what(?:'s| is) mira/i.test(m)) {
    return true;
  }
  if (/your story/i.test(m) && /mira/i.test(m)) return true;
  if (/^(hi[,!.\s]*)?(who are you|မင်းဘယ်သူ(?:လဲ)?|နင်ဘယ်သူ(?:လဲ)?|သင်ဘယ်သူ(?:လဲ)?|ဘယ်သူလဲ)\??\.?$/i.test(m)) {
    return true;
  }
  return false;
}

/**
 * @param {string} [userMessage]
 * @param {'quick' | 'deep' | 'wise' | string} [mode]
 */
export function shouldUseConciseMiraStory(userMessage, mode) {
  if (mode === 'quick') return true;
  const m = String(userMessage || '').trim();
  if (m.length <= 28 && /who are you|ဘယ်သူ/i.test(m)) return true;
  return false;
}

/**
 * @param {{ locale?: 'en' | 'my' | 'id' | string; concise?: boolean; userName?: string }} [opts]
 */
export function getMiraStoryAnswer(opts = {}) {
  const locale = opts.locale === 'my' ? 'my' : 'en';
  const concise = Boolean(opts.concise);
  const name = String(opts.userName || '').trim();

  let body =
    locale === 'my'
      ? concise
        ? MIRA_STORY_ANSWER_MY_SHORT
        : MIRA_STORY_ANSWER_MY
      : concise
        ? MIRA_STORY_ANSWER_EN_SHORT
        : MIRA_STORY_ANSWER_EN;

  if (name && locale === 'my' && !concise) {
    body = `${name} မေးတဲ့အတွက် ကျေးဇူးတင်ပါတယ်။\n\n${body}`;
  } else if (name && locale === 'en' && !concise) {
    body = `${name}, thanks for asking.\n\n${body}`;
  }

  return body;
}

