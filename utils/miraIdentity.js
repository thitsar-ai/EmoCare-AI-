/**
 * @param {string} [userMessage]
 */
export function isMiraBirthdayQuestion(userMessage) {
  const m = String(userMessage || '').trim();
  if (!m) return false;
  if (/same birthday|both (?:have )?the same birthday|emo'?s birthday|birthday.+emo|emo.+birthday/i.test(m)) {
    return true;
  }
  if (/when (?:is|was) your birthday|what(?:'s| is) your birthday|your birthday|mira'?s birthday|birthday[,!.\s]*mira?/i.test(m)) {
    return true;
  }
  if (/မွေးနေ့|မွေးနေ့က/.test(m)) return true;
  return false;
}

