/**
 * @param {string} intent
 * @param {number} [limit]
 */
export function selectBurmeseExamples(intent, limit = 4) {
  const matched = EMO_BURMESE_EXAMPLES.filter((ex) => ex.intent === intent);
  const fallback = EMO_BURMESE_EXAMPLES.filter((ex) =>
    ['greeting', 'emotional_disclosure', 'casual', 'just_listen'].includes(ex.intent),
  );
  const pool = matched.length ? matched : fallback;
  return pool.slice(0, limit);
}

/**
 * @param {string} intent
 */
export function formatBurmeseExamplesForPrompt(intent) {
  const examples = selectBurmeseExamples(intent, 4);
  if (!examples.length) return '';
  const lines = examples.map(
    (ex, i) => `Example ${i + 1}\nUser: ${ex.user}\nAssistant: ${ex.assistant}`,
  );
  return `## BURMESE FEW-SHOT (intent: ${intent} — imitate style, do not copy blindly)\n${lines.join('\n\n')}`;
}

export function burmeseExampleCount() {
  return EMO_BURMESE_EXAMPLES.length;
}
